"""Заглушки реализаций команд для эмулятора оболочки.

Каждая команда получает список аргументов, разобранных из ввода пользователя,
и возвращает строку, которая будет отображена в окне терминала.
"""


def cmd_ls(args: list[str]) -> str:
    """Заглушка для UNIX-команды `ls`.

    Возвращает имя команды вместе с полученными аргументами.
    """
    return f"ls: command received, args={args}"


def cmd_cd(args: list[str]) -> str:
    """Заглушка для UNIX-команды `cd`.

    Возвращает имя команды вместе с полученными аргументами.
    """
    return f"cd: command received, args={args}"


def cmd_exit(args: list[str]) -> str:
    """Сообщает оболочке о необходимости завершения.

    Фактическое завершение обрабатывается вызывающей стороной;
    эта функция лишь формирует прощальное сообщение.
    """
    return "exit: shutting down..."
